static int16_t teamarg_fat_small_index(char ch)
{
  uint8_t c = ch;
  return (c >= TEAMARG_FAT_SMALL_FIRST && c <= TEAMARG_FAT_SMALL_LAST) ? (int16_t)(c - TEAMARG_FAT_SMALL_FIRST) : -1;
}

// Negative letter gap: the letters overlap, so they are drawn from the last to the first and every
// letter ends up on top of the next one (its white and black pixels cover it, its transparent pixels show it).
// Draws a string at x,y. Set inFlash to true for a PROGMEM string. No line breaks.
void teamarg_fat_small_drawText(int16_t x, int16_t y, const char *s, bool inFlash = false)
{
  uint8_t n = 0;
  while (inFlash ? pgm_read_byte(s + n) : s[n]) n++;
  int16_t e = x + n * (TEAMARG_FAT_SMALL_WIDTH + TEAMARG_FAT_SMALL_SPACING);
  for (uint8_t j = n; j > 0;)
  {
    j--;
    char c = inFlash ? pgm_read_byte(s + j) : s[j];
    int16_t i = teamarg_fat_small_index(c);
    uint8_t w = TEAMARG_FAT_SMALL_WIDTH;
    e -= w + TEAMARG_FAT_SMALL_SPACING;
    if (i >= 0) Sprites::drawPlusMask(e, y, teamarg_fat_small_plus_mask, i);
  }
}

